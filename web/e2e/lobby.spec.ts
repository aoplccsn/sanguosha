test('eight-seat invite retains a guest seat after refresh', async ({ browser }) => {
  const hostContext = await browser.newContext()
  const guestContext = await browser.newContext()
  const host = await hostContext.newPage()
  const guest = await guestContext.newPage()
  try {
    await host.goto('/')
    await host.getByLabel('玩家昵称').fill('房主')
    await host.getByLabel('对局模式').selectOption('military-eight')
    await expect(host.getByLabel('对局模式')).toHaveValue('military-eight')
    await host.getByRole('button', { name: '创建多人房间' }).click()
    const roomCode = (await host.locator('.room-code-box strong').textContent())?.trim()
    expect(roomCode).toMatch(/^[A-Z0-9]{6}$/)
    await expect(host.locator('.lobby-seat')).toHaveCount(8)
    await guest.goto('/room/' + roomCode)
    await guest.getByLabel('玩家昵称').fill('来宾')
    await guest.getByRole('button', { name: '加入房间' }).click()
    await guest.getByRole('button', { name: '准备' }).click()
    await expect(host.locator('.lobby-seat').filter({ hasText: '来宾' })).toContainText('已准备')
    await guest.reload()
    await expect(guest.locator('.lobby-seat')).toHaveCount(8)
    await expect(guest.locator('.lobby-seat').filter({ hasText: '来宾' })).toContainText('已准备')
    await host.getByRole('button', { name: '开始游戏' }).click()
    await expect(host.getByRole('heading', { name: '择将入局' })).toBeVisible()
    await expect(guest.getByRole('heading', { name: '择将入局' })).toBeVisible()
  } finally {
    await hostContext.close()
    await guestContext.close()
  }
})

