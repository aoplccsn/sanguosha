test('full eight-human room lets a refreshed browser reclaim its seat', async ({ browser }) => {
  test.setTimeout(120000)
  const contexts = await Promise.all(Array.from({ length: 8 }, () => browser.newContext()))
  try {
    const pages = await Promise.all(contexts.map((context) => context.newPage()))
    await pages[0].goto('/')
    await pages[0].getByLabel('玩家昵称').fill('玩家1')
    await pages[0].getByLabel('对局模式').selectOption('military-eight')
    await pages[0].getByRole('button', { name: '创建多人房间' }).click()
    const roomCode = (await pages[0].locator('.room-code-box strong').textContent())?.trim()
    expect(roomCode).toMatch(/^[A-Z0-9]{6}$/)
    for (let index = 1; index < pages.length; index += 1) {
      await pages[index].goto('/room/' + roomCode)
      await pages[index].getByLabel('玩家昵称').fill('玩家' + (index + 1))
      await pages[index].getByRole('button', { name: '加入房间' }).click()
      await pages[index].getByRole('button', { name: '准备' }).click()
    }
    await expect(pages[0].locator('.lobby-seat.human')).toHaveCount(8)
    await pages[0].getByRole('button', { name: '开始游戏' }).click()
    for (const page of pages) {
      await expect(page.getByRole('heading', { name: '择将入局' })).toBeVisible()
      await page.locator('.general-card').first().click()
      await page.getByRole('button', { name: '确认武将' }).click()
    }
    await expect(pages[7].locator('.game-page')).toBeVisible()
    await expect(pages[7].locator('.player-panel')).toHaveCount(8)
    await pages[7].reload()
    await expect(pages[7].locator('.game-page')).toBeVisible()
    await expect(pages[7].locator('.player-self')).toContainText('你 · 玩家8')
    await expect(pages[7].locator('.player-panel')).toHaveCount(8)
    await expect(pages[0].locator('.player-panel')).toHaveCount(8)
  } finally {
    for (const context of contexts) await context.close()
  }
})
